import type { Answer, Category, Prompt, Score } from "../types";

// Independently written practice prompts. Familiarity scores are editorial
// estimates; an answer need not appear here to satisfy a prompt's factual scope.
function answers(tiers: Partial<Record<Score, string>>): Answer[] {
  return Object.entries(tiers).flatMap(([score, names]) =>
    names!.split(";").map((entry) => {
      const [name, ...aliases] = entry.split("=").map((part) => part.trim());
      return {
        name,
        score: Number(score) as Score,
        ...(aliases.length ? { aliases } : {}),
      };
    }),
  );
}
function q(
  id: string,
  category: Category,
  prompt: string,
  note: string,
  tiers: Partial<Record<Score, string>>,
  source?: string,
): Prompt {
  return {
    id: `extra-${id}`,
    category,
    prompt,
    note,
    answers: answers(tiers),
    ...(source ? { source } : {}),
  };
}

